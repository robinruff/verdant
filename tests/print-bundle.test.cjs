const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const source=fs.readFileSync(path.join(root,'public/zip-backup.js'),'utf8');
const context=vm.createContext({Blob,Uint8Array,Uint32Array,DataView,TextEncoder,TextDecoder,Date,globalThis:{}});
vm.runInContext(source,context);
const Z=context.globalThis.VerdantZip;
(async()=>{
  const included=fs.readdirSync(path.join(root,'public/print')).sort();
  assert.deepEqual([...Z.printFiles].sort(),included,'Export manifest must match bundled print files');
  assert(Z.printFiles.includes('printout.typ'));
  assert(!Z.printFiles.includes('handover.typ'));
  const readme=fs.readFileSync(path.join(root,'public/print/README.md'),'utf8');
  assert(readme.includes('typst compile printout.typ garden-printout.pdf'));
  assert(readme.includes('https://verdant.robin-ruff-98.workers.dev'));
  assert(readme.includes('data.plants') && readme.includes('data.images'));
  const typst=fs.readFileSync(path.join(root,'public/print/printout.typ'),'utf8');
  assert(typst.includes('https://verdant.robin-ruff-98.workers.dev'));
  assert(typst.includes('#link(editor-url)[#editor-url]'));
  assert(typst.includes('#show link: underline'));
  assert(typst.includes('import the exported ZIP'));
  assert((typst.match(/#link\(editor-url\)/g)||[]).length>=4,'Editor link should appear in first-page text and page footers');
  const manager=fs.readFileSync(path.join(root,'src/settings/manager.js'),'utf8');
  const backupTool=fs.readFileSync(path.join(root,'src/settings/backup-tool.js'),'utf8');
  assert(!/typst|printout/i.test(manager),'PWA backup screen should stay focused on backup/restore');
  assert(!/typst compile|ready-to-compile Typst report/i.test(backupTool),'PWA status should not contain print instructions');
  for(const name of Z.printFiles)assert(fs.statSync(path.join(root,'public/print',name)).size>0);
  const data={format:'verdant-garden-backup',schemaVersion:2,exportedAt:'2026-10-30T20:00:00Z',data:{plants:[],plantTypes:[],images:[],settings:[]}};
  const base={path:'data.json',blob:new Blob([JSON.stringify(data)])};
  const print=Z.printFiles.map(name=>({path:name,blob:new Blob([fs.readFileSync(path.join(root,'public/print',name))])}));
  const zipOf=async entries=>{
    const parts=[];
    await Z.writeZip({async write(bytes){parts.push(bytes)},async close(){}},entries);
    return new Blob(parts);
  };
  const legacy=await zipOf([base]);
  const parsedLegacy=await Z.parseVerdantZip(legacy);
  assert.equal(parsedLegacy.data.images.length,0,'Old data-only ZIP must still restore');
  const newZip=await zipOf([base,...print]);
  const parsed=await Z.parseVerdantZip(newZip);
  assert.equal(parsed.data.images.length,0);
  const decoded=await Z.openZip(newZip);
  assert(decoded.entries.has('printout.typ'));
  assert(decoded.entries.has('README.md'));
  assert(!decoded.entries.has('PRINT_README.txt'));
  assert.equal(decoded.entries.size,Z.printFiles.length+1);
  assert.equal((await decoded.entries.get('printout.typ').blob.text()).slice(0,10),'// Verdant');
  const legacyPrint=print.map(entry=>entry.path==='README.md'?{path:'PRINT_README.txt',blob:new Blob(['VERDANT — GARDEN PRINTOUT legacy instructions'])}:entry);
  const previousZip=await zipOf([base,...legacyPrint]);
  const previous=await Z.parseVerdantZip(previousZip);
  assert.equal(previous.schemaVersion,2,'Previous print-bundled ZIP must still restore');
  const mixedZip=await zipOf([base,...print,{path:'PRINT_README.txt',blob:new Blob(['old instructions'])}]);
  await assert.rejects(()=>Z.parseVerdantZip(mixedZip),/Incomplete Typst/);
  const partialZip=await zipOf([base,print[0]]);
  await assert.rejects(()=>Z.parseVerdantZip(partialZip),/Incomplete Typst/);
  const unknownZip=await zipOf([base,{path:'suspicious-file.txt',blob:new Blob(['hi'])}]);
  await assert.rejects(()=>Z.parseVerdantZip(unknownZip),/Unexpected file/);
  const tampered=Buffer.from(await newZip.arrayBuffer());
  const marker=Buffer.from('# Verdant garden backup and printout');
  const at=tampered.indexOf(marker);
  assert(at>=0,'Print instructions must be part of the ZIP');
  tampered[at]^=1;
  await assert.rejects(()=>Z.parseVerdantZip(new Blob([tampered])),/CRC mismatch/);
  console.log('PASS: print README, PDF editor link, quiet PWA, and restored old/new ZIPs; unknown/partial/corrupt entries rejected');
})().catch(e=>{console.error(e);process.exitCode=1});
