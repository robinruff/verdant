const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const html = read('index.html');
const entry = read('src/main.js');
const pkg = require('../package.json');
assert.equal(pkg.version, '1.6.7');
assert.match(html, /VERDANT · LOCAL FIRST · VERSION 1\.6\.7 · VUE 3/);
assert.match(html, /<title>Verdant 1\.6\.7/);
assert.equal(pkg.dependencies['maplibre-gl'], '6.16.0');
assert.match(entry, /from 'maplibre-gl'/);
assert.match(entry, /maplibre-gl\/dist\/maplibre-gl\.css/);
assert.match(entry, /window\.maplibregl\s*=/);
assert.match(html, /src="\.\/src\/main\.js"/);
assert.doesNotMatch(html, /fetch_maplibre|fetch-maplibre|vendor\/maplibre-gl/);
assert.match(read('scripts/write-sw.mjs'), /verdant-shell-v1\.6\.7/);
assert.match(read('scripts/write-sw.mjs'), /photo-optimizer\.js\?v=1\.6\.7/);
assert.match(html, /photo-optimizer\.js\?v=1\.6\.7/);
assert.match(read('app.js'), /DB_NAME = 'verdant-garden-v2'/);
assert.match(read('app.js'), /BACKUP_SCHEMA = 2/);
