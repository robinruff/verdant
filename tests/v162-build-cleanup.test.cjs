for (const file of publish) assert(!/^(?:backup-v\d|photos-v\d|settings-tools-v\d|fetch[-_]maplibre|enrich)/.test(file), 'legacy public asset: '+file);
assert(fs.existsSync(path.join(root, 'public/verdant-rescue.html')));
assert(!fs.existsSync(path.join(root, 'public/vendor/maplibre-gl.js')));
